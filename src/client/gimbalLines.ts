export function pickGimbalLine(previous?: string): string {
  const candidates = previous && GIMBAL_LINES.length > 1
    ? GIMBAL_LINES.filter((line) => line !== previous)
    : GIMBAL_LINES
  return candidates[Math.floor(Math.random() * candidates.length)] ?? GIMBAL_LINES[0]
}
